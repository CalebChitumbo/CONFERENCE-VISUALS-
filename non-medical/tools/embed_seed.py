#!/usr/bin/env python3
"""Embed the line-up photos and logos into index.html as data URLs.

Run from anywhere:  python3 non-medical/tools/embed_seed.py
Reads   non-medical/photos/*.jpg  (square, face-centred; key = file name without extension)
        non-medical/logos/conf_logo_transparent.png, rpa_logo.png
        non-medical/fonts/*.woff2  (brand fonts, SIL Open Font License, latin subset)
Writes  the block between the SEED:BEGIN / SEED:END markers in non-medical/index.html.
Needs Pillow (pip install pillow) to shrink the logos to WebP.
"""
import base64, io, json, pathlib, re
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
HTML = ROOT / 'index.html'


def data_url(raw, mime):
    return f'data:{mime};base64,' + base64.b64encode(raw).decode()


def logo(path, size):
    im = Image.open(path).convert('RGBA')
    im.thumbnail((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'WEBP', quality=92, method=6, alpha_quality=100)
    return data_url(buf.getvalue(), 'image/webp')


seed = {
    'logos': {
        'conf': logo(ROOT / 'logos' / 'conf_logo_transparent.png', 600),
        'rpa': logo(ROOT / 'logos' / 'rpa_logo.png', 256),
    },
    'photos': {p.stem: data_url(p.read_bytes(), 'image/jpeg')
               for p in sorted((ROOT / 'photos').glob('*.jpg'))},
}

FONTS = [  # (file, family, weight, style)
    ('cinzel-latin-600-normal', 'Cinzel', 600, 'normal'),
    ('cinzel-latin-700-normal', 'Cinzel', 700, 'normal'),
    ('inter-latin-400-normal', 'Inter', 400, 'normal'),
    ('inter-latin-500-normal', 'Inter', 500, 'normal'),
    ('inter-latin-600-normal', 'Inter', 600, 'normal'),
    ('inter-latin-700-normal', 'Inter', 700, 'normal'),
    ('playfair-display-latin-400-italic', 'Playfair Display', 400, 'italic'),
    ('roboto-mono-latin-400-normal', 'Roboto Mono', 400, 'normal'),
    ('roboto-mono-latin-500-normal', 'Roboto Mono', 500, 'normal'),
]
faces = '\n'.join(
    f"@font-face{{font-family:'{fam}';font-style:{sty};font-weight:{wt};font-display:block;"
    f"src:url({data_url((ROOT / 'fonts' / (f + '.woff2')).read_bytes(), 'font/woff2')}) format('woff2');}}"
    for f, fam, wt, sty in FONTS)

block = ('<!-- SEED:BEGIN — generated by tools/embed_seed.py; do not edit by hand -->\n'
         '<style>\n' + faces + '\n</style>\n'
         '<script>window.RPO_SEED = ' + json.dumps(seed, indent=0) + ';</script>\n'
         '<!-- SEED:END -->')
html = HTML.read_text(encoding='utf-8')
html, n = re.subn(r'<!-- SEED:BEGIN.*?<!-- SEED:END -->', lambda _: block, html, flags=re.S)
assert n == 1, 'SEED markers not found in index.html'
HTML.write_text(html, encoding='utf-8')
print(f"Embedded {len(seed['photos'])} photos + 2 logos + {len(FONTS)} fonts -> {HTML} ({HTML.stat().st_size // 1024} KB)")
